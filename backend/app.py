def user_owns_document(user_id, filename):
    connection = get_db_connection()
    try:
        cursor = connection.cursor()
        db_execute(cursor, 
            """
            SELECT 1
            FROM user_documents
            WHERE user_id = ? AND filename = ?
            """,
            (user_id, secure_filename(filename)),
        )
        return cursor.fetchone() is not None
    finally:
        connection.close()


