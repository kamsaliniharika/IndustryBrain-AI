# --------------------------------------------------
# Text Quality Check and Document Extraction
# --------------------------------------------------

def is_text_usable(text):
    """Return True when extracted text is substantial enough to use directly."""
    if not text or len(text.strip()) < 20:
        return False

    stripped = text.strip()
    alphanumeric = sum(char.isalnum() for char in stripped)
    ratio = alphanumeric / max(len(stripped), 1)
    return ratio >= 0.45


def _native_text_is_good_enough(text):
    """Avoid expensive OCR when a PDF page already has meaningful native text."""
    if is_text_usable(text):
        return True

    stripped = (text or "").strip()
    if len(stripped) < 80:
        return False

    alphanumeric = sum(char.isalnum() for char in stripped)
    ratio = alphanumeric / max(len(stripped), 1)
    # A less strict fallback prevents OCR timeouts on text-based PDFs whose
    # extracted layout or punctuation makes the strict quality check fail.
    return ratio >= 0.30


def extract_text_from_file(file_path):
    """Extract PDF, DOCX, or TXT text, using OCR only when it is needed.

    PDF pages with useful native text skip OCR. OCR is reserved for pages
    with no text or very little/low-quality text and has a short timeout so
    one difficult page cannot hold up the whole document for 30 seconds.
    """
    extension = os.path.splitext(file_path)[1].lower()

    if extension == ".pdf":
        extracted_pages = []
        file_name = os.path.basename(file_path)
        total_ocr_pages = 0
        total_ocr_timeouts = 0

        with fitz.open(file_path) as pdf:
            page_count = len(pdf)
            app.logger.info(
                "[EXTRACTION] Starting PDF extraction: %s pages, %s",
                page_count,
                file_name,
            )

            for page_number, page in enumerate(pdf, start=1):
                page_started = time.perf_counter()
                page_text = page.get_text("text", sort=True).strip()

                if _native_text_is_good_enough(page_text):
                    extracted_pages.append(page_text)
                    app.logger.debug(
                        "[EXTRACTION] Page %s used native text (%s chars)",
                        page_number,
                        len(page_text),
                    )
                    continue

                # If a page has a small amount of native text, preserve it as
                # a fallback in case OCR is slow or cannot recognize the page.
                fallback_text = page_text
                total_ocr_pages += 1

                try:
                    pix = page.get_pixmap(
                        matrix=fitz.Matrix(1.2, 1.2),
                        alpha=False,
                        colorspace=fitz.csRGB,
                    )
                    image = Image.frombytes(
                        "RGB",
                        (pix.width, pix.height),
                        pix.samples,
                    )
                    image = ImageOps.autocontrast(ImageOps.grayscale(image))

                    ocr_text = pytesseract.image_to_string(
                        image,
                        lang="eng",
                        config="--oem 1 --psm 3",
                        timeout=6,
                    ).strip()

                    if is_text_usable(ocr_text):
                        extracted_pages.append(ocr_text)
                    elif fallback_text:
                        extracted_pages.append(fallback_text)
                    elif ocr_text:
                        extracted_pages.append(ocr_text)

                except RuntimeError:
                    total_ocr_timeouts += 1
                    app.logger.warning(
                        "[OCR] Timed out after 6 seconds on page %s of %s; "
                        "keeping native text if available",
                        page_number,
                        file_name,
                    )
                    if fallback_text:
                        extracted_pages.append(fallback_text)

                except Exception:
                    app.logger.exception(
                        "[OCR] Failed on page %s of %s; "
                        "keeping native text if available",
                        page_number,
                        file_name,
                    )
                    if fallback_text:
                        extracted_pages.append(fallback_text)

                finally:
                    app.logger.debug(
                        "[TIMING] PDF page %s processed in %.2f seconds",
                        page_number,
                        time.perf_counter() - page_started,
                    )

        result = "\n\n".join(text for text in extracted_pages if text).strip()
        app.logger.info(
            "[EXTRACTION] Finished %s: chars=%s, OCR pages=%s, OCR timeouts=%s",
            file_name,
            len(result),
            total_ocr_pages,
            total_ocr_timeouts,
        )
        return result

    if extension == ".docx":
        document = Document(file_path)
        paragraphs = [
            paragraph.text.strip()
            for paragraph in document.paragraphs
            if paragraph.text.strip()
        ]
        return "\n".join(paragraphs).strip()

    if extension == ".txt":
        with open(
            file_path,
            "r",
            encoding="utf-8",
            errors="ignore",
        ) as file:
            return file.read().strip()

    return ""


# --------------------------------------------------
# Text Chunking
# --------------------------------------------------

def create_chunks(text, chunk_size=500, overlap=100):
    """Split extracted text into overlapping word chunks."""
    words = text.split()

    if not words:
        return []

    step = max(1, chunk_size - overlap)
    chunks = []

    for start in range(0, len(words), step):
        chunk = " ".join(words[start:start + chunk_size]).strip()
        if chunk:
            chunks.append(chunk)

    return chunks


# --------------------------------------------------
# Gemini Embeddings
# --------------------------------------------------

def create_embeddings(texts, task_type="RETRIEVAL_DOCUMENT"):
    """
    Create embeddings in batches to reduce the number of API requests.
    """
    if isinstance(texts, str):
        texts = [texts]

    if not texts:
        return np.empty((0, EMBEDDING_DIMENSION), dtype="float32")

    if not GEMINI_API_KEY:
        raise RuntimeError(
            "GEMINI_API_KEY is not configured in the backend environment."
        )

    all_embeddings = []
    total_start = time.perf_counter()

    for start in range(0, len(texts), EMBEDDING_BATCH_SIZE):
        batch = texts[start:start + EMBEDDING_BATCH_SIZE]
        batch_start = time.perf_counter()

        result = gemini_client.models.embed_content(
            model=EMBEDDING_MODEL,
            contents=batch,
            config=types.EmbedContentConfig(
                task_type=task_type,
                output_dimensionality=EMBEDDING_DIMENSION,
            ),
        )

        batch_embeddings = [
            embedding.values for embedding in result.embeddings
        ]

        if len(batch_embeddings) != len(batch):
            raise RuntimeError(
                "Gemini returned a different number of embeddings "
                "than the number of input texts."
            )

        all_embeddings.extend(batch_embeddings)

        app.logger.info(
            "[TIMING] Embedding batch: %s texts in %.2f seconds",
            len(batch),
            time.perf_counter() - batch_start,
        )

    app.logger.info(
        "[TIMING] Total embedding time: %.2f seconds for %s texts",
        time.perf_counter() - total_start,
        len(texts),
    )

    return np.asarray(all_embeddings, dtype="float32")


# --------------------------------------------------
# FAISS Index Creation
# --------------------------------------------------

def create_faiss_index(index_key, chunks):
    """Create a FAISS index unless a current index already exists."""
    if not chunks:
        raise ValueError("No text chunks were created from this document.")

    if index_key in documents:
        app.logger.info("[INDEX] Reusing existing index: %s", index_key)
        return documents[index_key]

    started = time.perf_counter()
    app.logger.info(
        "[INDEX] Creating embeddings for %s chunks",
        len(chunks),
    )

    embeddings = create_embeddings(
        chunks,
        task_type="RETRIEVAL_DOCUMENT",
    )

    if embeddings.size == 0:
        raise ValueError("Could not create embeddings for this document.")

    index = faiss.IndexFlatL2(embeddings.shape[1])
    index.add(embeddings)

    indexed_document = {
        "chunks": chunks,
        "index": index,
    }
    documents[index_key] = indexed_document

    app.logger.info(
        "[TIMING] Index creation finished in %.2f seconds; chunks=%s",
        time.perf_counter() - started,
        len(chunks),
    )

    return indexed_document


